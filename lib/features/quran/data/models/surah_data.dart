const int quranTotalPages = 604;

SurahModel surahForPage(int page) {
  var match = surahs.first;
  for (final surah in surahs) {
    if (surah.page <= page) {
      match = surah;
    } else {
      break;
    }
  }
  return match;
}

int clampQuranPage(int page, {int totalPages = quranTotalPages}) {
  if (totalPages < 1) {
    return 1;
  }
  if (page < 1) {
    return 1;
  }
  if (page > totalPages) {
    return totalPages;
  }
  return page;
}
